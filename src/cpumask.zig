//! `eb-local --cpu-target`: build for another CPU target on this machine.
//!
//! The target is an EESSI software subdirectory. A build for it runs in one of
//! four routes: `native` (the host already is the target), `cpuid` (the host
//! CPU shows the target's identity to every child process: CPUID faulting on
//! x86_64, a masked `getauxval` and `/proc/cpuinfo` on aarch64), `kvm` and
//! `tcg` (a virtual machine, run by `eb-local __vm-run`). This file holds the
//! target and profile data, the route choice, the preflight decision, the
//! files of the cpuid route and the provenance record. The process handling
//! stays in main.zig.
const std = @import("std");
const builtin = @import("builtin");
const linux = std.os.linux;
const common = @import("zig_common");
const sys = common.sys;
const fsx = common.fsx;
const proc = common.proc;
const Allocator = std.mem.Allocator;

/// Profile data, generated by tools/mask/gen_profiles.py.
const profiles_text = @embedFile("mask_profiles");
/// The preloaded libraries and the probe, compiled with the host's cc.
const cpuidmask_c = @embedFile("mask_cpuidmask_c");
const armmask_c = @embedFile("mask_armmask_c");
const probe_c = @embedFile("mask_probe_c");
/// EasyBuild hooks that chain the site's and pin the GROMACS SIMD level.
pub const hooks_py = @embedFile("mask_hooks_py");

/// The exit status of a process that cpuidmask stopped because the kernel has
/// no CPUID faulting and CPUIDMASK_STRICT is set.
pub const strict_exit: u8 = 97;

/// The architectures a CPU target can have.
pub const Arch = enum {
    x86_64,
    aarch64,

    /// The architecture this program runs on, null when it has no profile.
    pub fn host() ?Arch {
        return switch (builtin.cpu.arch) {
            .x86_64 => .x86_64,
            .aarch64 => .aarch64,
            else => null,
        };
    }
};

