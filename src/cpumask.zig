/// What a `--cpu-target` word names.
pub const Resolved = union(enum) {
    subdir: []const u8,
    /// A message for the user.
    refused: []const u8,
};

/// The subdirectory `text` names: a full subdirectory, or a short name that
/// one known subdirectory ends in.
pub fn resolveTarget(a: Allocator, text: []const u8) Resolved {
    const t = std.mem.trimEnd(u8, text, "/");
    if (t.len == 0) return .{ .refused = "--cpu-target needs a CPU target such as x86_64/amd/zen4 or zen4" };
    for (t) |ch| if (!(std.ascii.isAlphanumeric(ch) or ch == '/' or ch == '_' or ch == '-' or ch == '.'))
        return .{ .refused = "a CPU target holds letters, digits, '/', '_', '-' and '.' only" };
    for (known_subdirs) |k| if (std.mem.eql(u8, k, t)) return .{ .subdir = k };
    if (std.mem.indexOfScalar(u8, t, '/') != null) {
        if (std.mem.startsWith(u8, t, "x86_64/") or std.mem.startsWith(u8, t, "aarch64/"))
            return .{ .subdir = t };
        return .{ .refused = std.fmt.allocPrint(a, "'{s}' is not an EESSI CPU target; it starts with x86_64/ or aarch64/", .{t}) catch "unknown CPU target" };
    }
    var found: ?[]const u8 = null;
    var count: usize = 0;
    for (known_subdirs) |k| if (std.mem.eql(u8, std.fs.path.basename(k), t)) {
        found = k;
        count += 1;
    };
    if (count == 1) return .{ .subdir = found.? };
    if (count > 1) return .{ .refused = std.fmt.allocPrint(a, "'{s}' names more than one CPU target; give the architecture too, as x86_64/{s} or aarch64/{s}", .{ t, t, t }) catch "ambiguous CPU target" };
    return .{ .refused = std.fmt.allocPrint(a, "'{s}' is not a CPU target eb-local knows; give the EESSI subdirectory, for example x86_64/amd/zen4", .{t}) catch "unknown CPU target" };
}

/// The architecture a subdirectory is for.
pub fn archOf(subdir: []const u8) ?Arch {
    const slash = std.mem.indexOfScalar(u8, subdir, '/') orelse return null;
    return std.meta.stringToEnum(Arch, subdir[0..slash]);
}

// ---- profiles -------------------------------------------------------------

/// One target's identity, as `profiles.conf` records it.
pub const Profile = struct {
    subdir: []const u8,
    arch: Arch,
    vendor: []const u8 = "",
    family: u32 = 0,
    model: u32 = 0,
    model_name: []const u8 = "",
    gcc_march: []const u8 = "",
    host_vendors: []const []const u8 = &.{},
    needs: []const []const u8 = &.{},
    drop_flags: []const []const u8 = &.{},
    rules: []const []const u8 = &.{},
    cpu_part: []const u8 = "",
    gcc_cpu: []const u8 = "",
    features: []const []const u8 = &.{},
    hwcap: []const u8 = "0x0",
    hwcap2: []const u8 = "0x0",
};

fn words(a: Allocator, text: []const u8) []const []const u8 {
    var out: std.ArrayList([]const u8) = .empty;
    var it = std.mem.tokenizeAny(u8, text, " \t");
    while (it.next()) |w| out.append(a, w) catch @panic("out of memory");
    return out.items;
}

/// The profiles in `text`, in file order.
pub fn parseProfiles(a: Allocator, text: []const u8) []Profile {
    var out: std.ArrayList(Profile) = .empty;
    var rules: std.ArrayList([]const u8) = .empty;
    var cur: ?Profile = null;
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |raw| {
        const line = std.mem.trim(u8, raw, " \t\r");
        if (line.len == 0 or line[0] == '#') continue;
        if (line[0] == '[' and line[line.len - 1] == ']') {
            if (cur) |*p| {
                p.rules = rules.toOwnedSlice(a) catch @panic("out of memory");
                out.append(a, p.*) catch @panic("out of memory");
            }
            cur = .{ .subdir = line[1 .. line.len - 1], .arch = .x86_64 };
            continue;
        }
        const p = &(cur orelse continue);
        const eq = std.mem.indexOfScalar(u8, line, '=') orelse continue;
        const key = std.mem.trim(u8, line[0..eq], " \t");
        const val = std.mem.trim(u8, line[eq + 1 ..], " \t");
        if (std.mem.eql(u8, key, "arch")) {
            p.arch = std.meta.stringToEnum(Arch, val) orelse .x86_64;
        } else if (std.mem.eql(u8, key, "vendor")) {
            p.vendor = val;
        } else if (std.mem.eql(u8, key, "family")) {
            p.family = std.fmt.parseInt(u32, val, 10) catch 0;
        } else if (std.mem.eql(u8, key, "model")) {
            p.model = std.fmt.parseInt(u32, val, 10) catch 0;
        } else if (std.mem.eql(u8, key, "model_name")) {
            p.model_name = val;
        } else if (std.mem.eql(u8, key, "gcc_march")) {
            p.gcc_march = val;
        } else if (std.mem.eql(u8, key, "host_vendors")) {
            p.host_vendors = words(a, val);
        } else if (std.mem.eql(u8, key, "needs")) {
            p.needs = words(a, val);
        } else if (std.mem.eql(u8, key, "drop_flags")) {
            p.drop_flags = words(a, val);
        } else if (std.mem.eql(u8, key, "rule")) {
            rules.append(a, val) catch @panic("out of memory");
        } else if (std.mem.eql(u8, key, "cpu_part")) {
            p.cpu_part = val;
        } else if (std.mem.eql(u8, key, "gcc_cpu")) {
            p.gcc_cpu = val;
        } else if (std.mem.eql(u8, key, "features")) {
            p.features = words(a, val);
        } else if (std.mem.eql(u8, key, "hwcap")) {
            p.hwcap = val;
        } else if (std.mem.eql(u8, key, "hwcap2")) {
            p.hwcap2 = val;
        }
    }
    if (cur) |*p| {
        p.rules = rules.toOwnedSlice(a) catch @panic("out of memory");
        out.append(a, p.*) catch @panic("out of memory");
    }
    return out.items;
}

/// The profiles that ship with eb-local.
pub fn builtinProfiles(a: Allocator) []Profile {
    return parseProfiles(a, profiles_text);
}

/// The profile for `subdir`, or null.
pub fn findProfile(profiles: []const Profile, subdir: []const u8) ?Profile {
    for (profiles) |p| if (std.mem.eql(u8, p.subdir, subdir)) return p;
    return null;
}

/// The rule lines of `p` as cpuidmask reads them from CPUIDMASK_RULES.
pub fn rulesFile(a: Allocator, p: Profile) []const u8 {
    var out: std.ArrayList(u8) = .empty;
    for (p.rules) |r| {
        out.appendSlice(a, r) catch @panic("out of memory");
        out.append(a, '\n') catch @panic("out of memory");
    }
    return out.items;
}

// ---- the masked /proc/cpuinfo --------------------------------------------

fn hasWord(list: []const []const u8, w: []const u8) bool {
    for (list) |x| if (std.mem.eql(u8, x, w)) return true;
    return false;
}

/// `host`, the text of /proc/cpuinfo, as it reads on the target: the
/// identity fields of `p`, and without the flags `p` drops. Lines that name
/// nothing the profile changes stay as they are.
pub fn maskedCpuinfo(a: Allocator, p: Profile, host: []const u8) []const u8 {
    var out: std.ArrayList(u8) = .empty;
    var lines = std.mem.splitScalar(u8, host, '\n');
    var first = true;
    while (lines.next()) |line| {
        if (!first) out.append(a, '\n') catch @panic("out of memory");
        first = false;
        const colon = std.mem.indexOfScalar(u8, line, ':') orelse {
            out.appendSlice(a, line) catch @panic("out of memory");
            continue;
        };
        const key = std.mem.trim(u8, line[0..colon], " \t");
        const head = line[0 .. colon + 1];
        const value = std.mem.trim(u8, line[colon + 1 ..], " \t");
        var replaced: ?[]const u8 = null;
        switch (p.arch) {
            .x86_64 => {
                if (std.mem.eql(u8, key, "vendor_id")) {
                    replaced = p.vendor;
                } else if (std.mem.eql(u8, key, "cpu family")) {
                    replaced = std.fmt.allocPrint(a, "{d}", .{p.family}) catch @panic("out of memory");
                } else if (std.mem.eql(u8, key, "model")) {
                    replaced = std.fmt.allocPrint(a, "{d}", .{p.model}) catch @panic("out of memory");
                } else if (std.mem.eql(u8, key, "model name")) {
                    replaced = p.model_name;
                } else if (std.mem.eql(u8, key, "flags")) {
                    var kept: std.ArrayList(u8) = .empty;
                    var it = std.mem.tokenizeScalar(u8, value, ' ');
                    while (it.next()) |f| {
                        if (hasWord(p.drop_flags, f)) continue;
                        if (kept.items.len > 0) kept.append(a, ' ') catch @panic("out of memory");
                        kept.appendSlice(a, f) catch @panic("out of memory");
                    }
                    replaced = kept.items;
                }
            },
            .aarch64 => {
                if (std.mem.eql(u8, key, "Features")) {
                    replaced = std.mem.join(a, " ", p.features) catch @panic("out of memory");
                } else if (std.mem.eql(u8, key, "CPU part")) {
                    replaced = p.cpu_part;
                }
            },
        }
        out.appendSlice(a, head) catch @panic("out of memory");
        if (replaced) |r| {
            out.append(a, ' ') catch @panic("out of memory");
            out.appendSlice(a, r) catch @panic("out of memory");
        } else out.appendSlice(a, line[colon + 1 ..]) catch @panic("out of memory");
    }
    return out.items;
}

// ---- routes ---------------------------------------------------------------

/// What `--mask` asks for.
pub const Mode = enum { auto, cpuid, kvm, tcg };

/// How the build runs.
pub const Route = enum { native, cpuid, kvm, tcg };

/// What the choice of a route needs to know about this machine.
pub const Host = struct {
    arch: Arch,
    /// vendor_id of an x86_64 CPU, empty on aarch64.
    vendor: []const u8 = "",
    /// The `flags` (x86_64) or `Features` (aarch64) line of /proc/cpuinfo.
    flags: []const u8 = "",
    /// The EESSI subdirectory of this host, when it could be detected.
    subdir: ?[]const u8 = null,
    /// CPUID faulting works (x86_64).
    faulting: bool = false,
    /// /dev/kvm is usable.
    kvm: bool = false,
    /// `eb-local __vm-run` exists in this binary.
    vm_helper: bool = false,
};

/// The outcome of the route choice.
pub const Choice = union(enum) {
    route: Route,
    /// The message for the user.
    refuse: []const u8,
};

fn fmt(a: Allocator, comptime f: []const u8, args: anytype) []const u8 {
    return std.fmt.allocPrint(a, f, args) catch @panic("out of memory");
}

fn hostHasFlag(flags: []const u8, flag: []const u8) bool {
    var it = std.mem.tokenizeScalar(u8, flags, ' ');
    while (it.next()) |f| if (std.mem.eql(u8, f, flag)) return true;
    return false;
}

/// Why the cpuid route cannot present `target` on `host`, or null when it can.
pub fn cpuidProblem(a: Allocator, target: []const u8, profile: ?Profile, host: Host) ?[]const u8 {
    const p = profile orelse return fmt(a, "no mask profile exists for {s}", .{target});
    if (p.arch != host.arch)
        return fmt(a, "the cpuid route presents a CPU of this machine's architecture ({s}), not {s}", .{ @tagName(host.arch), @tagName(p.arch) });
    if (p.arch == .x86_64) {
        if (!host.faulting)
            return "CPUID faulting is not available here (Intel CPUs have it with Linux 4.12 and later, AMD CPUs with Linux 6.17 and later)";
        var allowed = false;
        for (p.host_vendors) |v| if (std.mem.eql(u8, v, host.vendor)) {
            allowed = true;
        };
        if (!allowed) return fmt(a, "the {s} profile cannot be shown on a {s} CPU", .{ target, host.vendor });
    }
    for (p.needs) |flag| if (!hostHasFlag(host.flags, flag))
        return fmt(a, "this CPU lacks {s}, which {s} has and a mask cannot add", .{ flag, target });
    return null;
}

/// The route for `target`. The target the host already is needs no mask.
pub fn choose(a: Allocator, mode: Mode, target: []const u8, profile: ?Profile, host: Host) Choice {
    if (host.subdir) |h| if (std.mem.eql(u8, h, target)) return .{ .route = .native };
    const arch = archOf(target) orelse return .{ .refuse = "the CPU target names no architecture" };
    const helper_missing = "this build of eb-local has no `__vm-run` helper, which the kvm and tcg routes call";
    switch (mode) {
        .cpuid => {
            if (cpuidProblem(a, target, profile, host)) |why| return .{ .refuse = why };
            return .{ .route = .cpuid };
        },
        .kvm => {
            if (arch != host.arch) return .{ .refuse = fmt(a, "kvm runs a CPU of this machine's architecture ({s}); {s} is {s}; use --mask tcg", .{ @tagName(host.arch), target, @tagName(arch) }) };
            if (!host.vm_helper) return .{ .refuse = helper_missing };
            if (!host.kvm) return .{ .refuse = "/dev/kvm is not usable by this user" };
            return .{ .route = .kvm };
        },
        .tcg => {
            if (!host.vm_helper) return .{ .refuse = helper_missing };
            return .{ .route = .tcg };
        },
        .auto => {
            if (arch != host.arch) {
                if (!host.vm_helper) return .{ .refuse = fmt(a, "{s} is another architecture than this machine ({s}), which only the tcg route reaches, and {s}", .{ target, @tagName(host.arch), helper_missing }) };
                return .{ .route = .tcg };
            }
            const why = cpuidProblem(a, target, profile, host) orelse return .{ .route = .cpuid };
            if (host.kvm and host.vm_helper) return .{ .route = .kvm };
            return .{ .refuse = fmt(a, "cannot present {s} here: {s}; kvm is {s}. --mask tcg emulates it, slowly", .{
                target,
                why,
                if (!host.vm_helper) "not built into this eb-local" else "not usable (/dev/kvm)",
            }) };
        },
    }
}

// ---- preflight ------------------------------------------------------------

/// What the build script saw inside the mask. A null field was not
/// observable: the tool is missing.
pub const Observed = struct {
    devfd: bool,
    /// The output of `eessi_archdetect.sh cpupath`: subdirectories separated by ':'.
    archdetect: ?[]const u8 = null,
    /// What archspec names the host, null when it cannot be imported.
    archspec: ?[]const u8 = null,
    /// The -march (x86_64) or -mcpu (aarch64) value of `gcc -march=native`.
    gcc: ?[]const u8 = null,
    /// The CPUID vendor string of a probe run in the mask.
    vendor: ?[]const u8 = null,
    /// Whether CPUID faulting is active in the probe.
    faulting: ?bool = null,
    /// `--mask-allow-archspec-mismatch`: an archspec name other than the target's is noted, not refused.
    archspec_allowed: bool = false,
};

/// One preflight check and what it found.
pub const Finding = struct { ok: bool, text: []const u8 };

/// The names archspec gives the targets whose archspec name differs from the
/// last component of the subdirectory.
fn archspecName(subdir: []const u8) []const u8 {
    if (std.mem.eql(u8, subdir, "aarch64/generic")) return "aarch64";
    if (std.mem.eql(u8, subdir, "x86_64/generic")) return "x86_64";
    return std.fs.path.basename(subdir);
}

/// Compare what the detectors report with `p`. Every detector must name the
/// target; a build that goes on with one that does not would install a tree
/// labelled for one CPU and compiled for another.
pub fn preflight(a: Allocator, p: Profile, route: Route, obs: Observed) []const Finding {
    var out: std.ArrayList(Finding) = .empty;
    const add = struct {
        fn f(list: *std.ArrayList(Finding), al: Allocator, ok: bool, comptime tmpl: []const u8, args: anytype) void {
            list.append(al, .{ .ok = ok, .text = fmt(al, tmpl, args) }) catch @panic("out of memory");
        }
    }.f;
    if (obs.devfd) {
        add(&out, a, true, "/dev/fd exists", .{});
    } else add(&out, a, false, "/dev/fd is missing, so EESSI archdetect fails on its process substitution and EESSI falls back to the generic target", .{});
    if (obs.archdetect) |ad| {
        const first = ad[0 .. std.mem.indexOfScalar(u8, ad, ':') orelse ad.len];
        const trimmed = std.mem.trim(u8, first, " \t\r\n");
        if (std.mem.eql(u8, trimmed, p.subdir)) {
            add(&out, a, true, "EESSI archdetect names {s}", .{p.subdir});
        } else add(&out, a, false, "EESSI archdetect names '{s}', not {s}", .{ trimmed, p.subdir });
    } else add(&out, a, false, "EESSI archdetect gave no answer", .{});
    if (obs.archspec) |sp| {
        const want = archspecName(p.subdir);
        if (std.mem.eql(u8, sp, want)) {
            add(&out, a, true, "archspec names {s}", .{want});
        } else if (obs.archspec_allowed) {
            add(&out, a, true, "archspec names '{s}', not {s}; accepted by --mask-allow-archspec-mismatch", .{ sp, want });
        } else add(&out, a, false, "archspec names '{s}', not {s}; an easyblock that asks archspec would build for another CPU than the tree is labelled for", .{ sp, want });
    } else add(&out, a, true, "archspec is not importable here; not checked", .{});
    const want_gcc = if (p.arch == .x86_64) p.gcc_march else p.gcc_cpu;
    const gcc_what = if (p.arch == .x86_64) "-march" else "-mcpu";
    if (obs.gcc) |g| {
        if (std.mem.eql(u8, g, want_gcc)) {
            add(&out, a, true, "gcc {s}=native is {s}", .{ gcc_what, want_gcc });
        } else add(&out, a, false, "gcc {s}=native is '{s}', not {s}", .{ gcc_what, g, want_gcc });
    } else add(&out, a, false, "gcc gave no {s}=native value", .{gcc_what});
    if (p.arch == .x86_64) {
        if (obs.vendor) |v| {
            if (std.mem.eql(u8, v, p.vendor)) {
                add(&out, a, true, "CPUID vendor is {s}", .{p.vendor});
            } else add(&out, a, false, "CPUID vendor is '{s}', not {s}", .{ v, p.vendor });
        } else add(&out, a, false, "the CPUID probe gave no answer", .{});
        if (route == .cpuid) {
            if (obs.faulting) |f| {
                if (f) {
                    add(&out, a, true, "CPUID faulting is active", .{});
                } else add(&out, a, false, "CPUID faulting is not active in the build; every CPUID would see the real CPU", .{});
            } else add(&out, a, false, "the probe did not say whether CPUID faulting is active", .{});
        }
    }
    return out.items;
}

/// Whether any finding refuses the build.
pub fn refused(findings: []const Finding) bool {
    for (findings) |f| if (!f.ok) return true;
    return false;
}

// ---- host facts -----------------------------------------------------------

/// The first value of `key` in /proc/cpuinfo text.
pub fn cpuinfoField(text: []const u8, key: []const u8) ?[]const u8 {
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |line| {
        const colon = std.mem.indexOfScalar(u8, line, ':') orelse continue;
        if (!std.mem.eql(u8, std.mem.trim(u8, line[0..colon], " \t"), key)) continue;
        return std.mem.trim(u8, line[colon + 1 ..], " \t");
    }
    return null;
}

/// Whether the kernel lets this process turn on CPUID faulting.
pub fn faultingAvailable() bool {
    if (builtin.cpu.arch != .x86_64) return false;
    const set_cpuid = 0x1012;
    if (linux.errno(linux.syscall2(.arch_prctl, set_cpuid, 0)) != .SUCCESS) return false;
    _ = linux.syscall2(.arch_prctl, set_cpuid, 1);
    return true;
}

/// Whether /dev/kvm can be opened for reading and writing.
pub fn kvmUsable() bool {
    return linux.errno(linux.faccessat(linux.AT.FDCWD, "/dev/kvm", linux.R_OK | linux.W_OK, 0)) == .SUCCESS;
}

/// The first `limit` bytes of the regular file `path`, or null.
pub fn readFile(a: Allocator, path: []const u8, limit: usize) ?[]const u8 {
    const f = fsx.openRegular(fsx.cwd, path, true) catch return null;
    defer sys.close(f.fd);
    return fsx.readAll(a, f.fd, limit) catch null;
}

/// This machine as the route choice sees it. `subdir` is the detected EESSI
/// subdirectory of the host, `vm_helper` whether `__vm-run` exists.
pub fn readHost(a: Allocator, subdir: ?[]const u8, vm_helper: bool) ?Host {
    const arch = Arch.host() orelse return null;
    const text = readFile(a, "/proc/cpuinfo", 4 << 20) orelse "";
    return .{
        .arch = arch,
        .vendor = cpuinfoField(text, "vendor_id") orelse "",
        .flags = cpuinfoField(text, if (arch == .x86_64) "flags" else "Features") orelse "",
        .subdir = subdir,
        .faulting = faultingAvailable(),
        .kvm = kvmUsable(),
        .vm_helper = vm_helper,
    };
}

/// A one-line name of the host CPU, for the provenance record.
pub fn hostModel(a: Allocator) []const u8 {
    const text = readFile(a, "/proc/cpuinfo", 4 << 20) orelse return "unknown";
    if (cpuinfoField(text, "model name")) |m| return m;
    if (cpuinfoField(text, "Model")) |m| return m;
    if (cpuinfoField(text, "CPU part")) |m| return fmt(a, "aarch64 CPU part {s}", .{m});
    return "unknown";
}

/// The running kernel's release, from /proc/sys/kernel/osrelease.
pub fn kernelRelease(a: Allocator) []const u8 {
    const text = readFile(a, "/proc/sys/kernel/osrelease", 256) orelse return "unknown";
    return std.mem.trim(u8, text, " \t\r\n");
}

// ---- the compiled preload libraries --------------------------------------

/// The compiled preload library and probe.
pub const Libs = struct {
    /// The preload library for the host architecture.
    preload: []const u8,
    probe: []const u8,
    dir: []const u8,
};

fn runText(a: Allocator, envp: proc.Envp, argv: []const []const u8, path_env: []const u8) ?[]const u8 {
    const exe = (proc.which(a, argv[0], path_env) catch null) orelse return null;
    const r = proc.run(a, exe, argv, envp, .{ .stdout_limit = 4096, .timeout_ms = 20_000 }) catch return null;
    if (r.term.code() != 0) return null;
    return std.mem.trim(u8, r.stdout, " \t\r\n");
}

fn writeNew(a: Allocator, path: []const u8, bytes: []const u8, mode: linux.mode_t) !void {
    const tmp = try std.fmt.allocPrint(a, "{s}.tmp.{d}", .{ path, linux.getpid() });
    const fd = try sys.openat(fsx.cwd, tmp, .{ .ACCMODE = .WRONLY, .CREAT = true, .TRUNC = true, .NOFOLLOW = true }, mode);
    var done = false;
    defer {
        sys.close(fd);
        if (!done) sys.unlinkat(fsx.cwd, tmp, 0) catch {};
    }
    try sys.writeAll(fd, bytes);
    try sys.renameat(fsx.cwd, tmp, fsx.cwd, path);
    done = true;
}

/// The cache key of the compiled libraries: the sources, the compiler's target
/// triple and the C library's version. A library built against one glibc does
/// not load into every other.
pub fn cacheKey(a: Allocator, triple: []const u8, libc: []const u8) []const u8 {
    var h = std.crypto.hash.sha2.Sha256.init(.{});
    for ([_][]const u8{ cpuidmask_c, armmask_c, probe_c, triple, libc }) |part| {
        h.update(part);
        h.update("\x00");
    }
    var digest: [32]u8 = undefined;
    h.final(&digest);
    return fmt(a, "{x}", .{digest[0..8]});
}

/// The preload library and probe for this host, compiled with the host's cc
/// into `cache_home/eb-local/mask-KEY` on first use. A static binary cannot be
/// preloaded into the dynamically linked programs of a build, so the library
/// is built from the C source embedded here.
pub fn ensureLibs(a: Allocator, envp: proc.Envp, path_env: []const u8, cache_home: []const u8, failure: *[]const u8) ?Libs {
    const arch = Arch.host() orelse {
        failure.* = "this machine's architecture has no mask library";
        return null;
    };
    const triple = runText(a, envp, &.{ "cc", "-dumpmachine" }, path_env) orelse {
        failure.* = "no C compiler (cc) on PATH; the cpuid route compiles its preload library with it";
        return null;
    };
    const libc = runText(a, envp, &.{ "getconf", "GNU_LIBC_VERSION" }, path_env) orelse "unknown";
    const key = cacheKey(a, triple, libc);
    const dir = std.fmt.allocPrint(a, "{s}/eb-local/mask-{s}", .{ cache_home, key }) catch @panic("out of memory");
    const lib_name = if (arch == .x86_64) "libcpuidmask.so" else "libarmmask.so";
    const preload = std.fmt.allocPrint(a, "{s}/{s}", .{ dir, lib_name }) catch @panic("out of memory");
    const probe = std.fmt.allocPrint(a, "{s}/cpuid-probe", .{dir}) catch @panic("out of memory");
    const libs: Libs = .{ .preload = preload, .probe = probe, .dir = dir };
    if (isFile(preload) and isFile(probe)) return libs;

    common.atomic.makedirs(dir) catch |e| {
        failure.* = fmt(a, "cannot create {s} ({s})", .{ dir, sys.describe(e) });
        return null;
    };
    const cc = (proc.which(a, "cc", path_env) catch null) orelse {
        failure.* = "no C compiler (cc) on PATH";
        return null;
    };
    const lib_src_name = if (arch == .x86_64) "cpuidmask.c" else "armmask.c";
    const lib_src = if (arch == .x86_64) cpuidmask_c else armmask_c;
    const lib_src_path = fmt(a, "{s}/{s}", .{ dir, lib_src_name });
    const probe_src_path = fmt(a, "{s}/cpuid-probe.c", .{dir});
    writeNew(a, lib_src_path, lib_src, 0o600) catch |e| {
        failure.* = fmt(a, "cannot write {s} ({s})", .{ lib_src_path, @errorName(e) });
        return null;
    };
    writeNew(a, probe_src_path, probe_c, 0o600) catch |e| {
        failure.* = fmt(a, "cannot write {s} ({s})", .{ probe_src_path, @errorName(e) });
        return null;
    };
    const tmp_lib = fmt(a, "{s}.tmp.{d}", .{ preload, linux.getpid() });
    const tmp_probe = fmt(a, "{s}.tmp.{d}", .{ probe, linux.getpid() });
    const builds = [_][]const []const u8{
        &.{ cc, "-O2", "-shared", "-fPIC", "-o", tmp_lib, lib_src_path, "-ldl" },
        &.{ cc, "-O2", "-o", tmp_probe, probe_src_path },
    };
    for (builds) |argv| {
        const r = proc.run(a, cc, argv, envp, .{ .stdout_limit = 4096, .stderr_limit = 8192, .timeout_ms = 120_000 }) catch |e| {
            failure.* = fmt(a, "cannot run {s} ({s})", .{ cc, @errorName(e) });
            return null;
        };
        if (r.term.code() != 0) {
            failure.* = fmt(a, "{s} failed building the mask library:\n{s}", .{ cc, r.stderr });
            return null;
        }
    }
    sys.renameat(fsx.cwd, tmp_lib, fsx.cwd, preload) catch |e| {
        failure.* = fmt(a, "cannot install {s} ({s})", .{ preload, sys.describe(e) });
        return null;
    };
    sys.renameat(fsx.cwd, tmp_probe, fsx.cwd, probe) catch |e| {
        failure.* = fmt(a, "cannot install {s} ({s})", .{ probe, sys.describe(e) });
        return null;
    };
    return libs;
}

fn isFile(path: []const u8) bool {
    const st = fsx.statAt(fsx.cwd, path, true) catch return false;
    return st.isReg();
}

// ---- the command the build runs ------------------------------------------

/// The words in front of the build command for the cpuid route: an
/// unprivileged user and mount namespace that keeps the caller's uid (a
/// mapped root makes OpenMPI's prterun refuse to start), with `fake` bound
/// over /proc/cpuinfo. The ambient capabilities the namespace gives are
/// dropped before the command runs when `setpriv` exists.
pub fn namespaceWords(a: Allocator, unshare: []const u8, setpriv: ?[]const u8, fake: []const u8) []const []const u8 {
    const script = if (setpriv != null)
        "mount --bind \"$0\" /proc/cpuinfo || exit 98; exec \"$1\" --ambient-caps=-all --inh-caps=-all \"${@:2}\""
    else
        "mount --bind \"$0\" /proc/cpuinfo || exit 98; exec \"$@\"";
    var out: std.ArrayList([]const u8) = .empty;
    out.appendSlice(a, &.{ unshare, "--user", "--map-current-user", "--keep-caps", "--mount", "--propagation", "slave", "bash", "-c", script, fake }) catch @panic("out of memory");
    if (setpriv) |s| out.append(a, s) catch @panic("out of memory");
    return out.items;
}

/// The variables the masked command gets.
pub fn maskVariables(a: Allocator, p: Profile, libs: Libs, rules_path: []const u8, hooks_path: []const u8, self_exe: []const u8, route: Route, allow_archspec: bool) []const [2][]const u8 {
    var out: std.ArrayList([2][]const u8) = .empty;
    const add = struct {
        fn f(list: *std.ArrayList([2][]const u8), al: Allocator, k: []const u8, v: []const u8) void {
            list.append(al, .{ k, v }) catch @panic("out of memory");
        }
    }.f;
    add(&out, a, "EB_LOCAL_CPU_TARGET", p.subdir);
    add(&out, a, "EB_LOCAL_MASK_ROUTE", @tagName(route));
    if (allow_archspec) add(&out, a, "EB_LOCAL_ALLOW_ARCHSPEC", "1");
    add(&out, a, "EB_LOCAL_PROBE", libs.probe);
    add(&out, a, "EB_LOCAL_SELF", self_exe);
    add(&out, a, "EB_LOCAL_HOOKS_FILE", hooks_path);
    add(&out, a, "EESSI_SOFTWARE_SUBDIR_OVERRIDE", p.subdir);
    if (route == .cpuid) {
        add(&out, a, "LD_PRELOAD", libs.preload);
        if (p.arch == .x86_64) {
            add(&out, a, "CPUIDMASK_RULES", rules_path);
            add(&out, a, "CPUIDMASK_STRICT", "1");
        } else {
            add(&out, a, "ARMMASK_HWCAP", p.hwcap);
            add(&out, a, "ARMMASK_HWCAP2", p.hwcap2);
        }
    }
    return out.items;
}

// ---- provenance -----------------------------------------------------------

fn jsonString(a: Allocator, out: *std.ArrayList(u8), s: []const u8) void {
    out.append(a, '"') catch @panic("out of memory");
    for (s) |ch| switch (ch) {
        '"' => out.appendSlice(a, "\\\"") catch @panic("out of memory"),
        '\\' => out.appendSlice(a, "\\\\") catch @panic("out of memory"),
        '\n' => out.appendSlice(a, "\\n") catch @panic("out of memory"),
        0...9, 11...31 => out.print(a, "\\u{x:0>4}", .{ch}) catch @panic("out of memory"),
        else => out.append(a, ch) catch @panic("out of memory"),
    };
    out.append(a, '"') catch @panic("out of memory");
}

/// What `easybuild/eb-local-build-mode.json` records.
pub const Provenance = struct {
    target: []const u8,
    route: Route,
    /// The profile's subdirectory, empty for a route without one.
    profile: []const u8,
    host_cpu: []const u8,
    kernel: []const u8,
    version: []const u8,
    /// "pass", "fail" or "skipped".
    audit: []const u8,
};

/// The text of easybuild/eb-local-build-mode.json.
pub fn provenanceJson(a: Allocator, p: Provenance) []const u8 {
    var out: std.ArrayList(u8) = .empty;
    out.appendSlice(a, "{\n") catch @panic("out of memory");
    const fields = [_][2][]const u8{
        .{ "cpu_target", p.target },
        .{ "route", @tagName(p.route) },
        .{ "profile", p.profile },
        .{ "host_cpu", p.host_cpu },
        .{ "kernel", p.kernel },
        .{ "eb_local_version", p.version },
        .{ "isa_audit", p.audit },
    };
    for (fields, 0..) |f, i| {
        out.appendSlice(a, "  ") catch @panic("out of memory");
        jsonString(a, &out, f[0]);
        out.appendSlice(a, ": ") catch @panic("out of memory");
        jsonString(a, &out, f[1]);
        out.appendSlice(a, if (i + 1 < fields.len) ",\n" else "\n") catch @panic("out of memory");
    }
    out.appendSlice(a, "}\n") catch @panic("out of memory");
    return out.items;
}

/// Write `text` as `dir/name`, replacing what is there.
pub fn writeProvenance(a: Allocator, dir: []const u8, text: []const u8) bool {
    const path = fmt(a, "{s}/eb-local-build-mode.json", .{dir});
    writeNew(a, path, text, 0o644) catch return false;
    return true;
}

/// Write `bytes` to `path` with `mode`, replacing what is there.
pub fn writeFile(a: Allocator, path: []const u8, bytes: []const u8, mode: linux.mode_t) bool {
    writeNew(a, path, bytes, mode) catch return false;
    return true;
}

