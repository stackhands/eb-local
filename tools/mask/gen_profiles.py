"""Write share/eb-local/mask/profiles.conf from targets.toml and rules/*.rules.

    python tools/mask/gen_profiles.py > share/eb-local/mask/profiles.conf

The output is the file eb-local embeds. One [SUBDIR] section per target, one
`key = value` per line; an x86_64 target's CPUID rules follow as repeated
`rule = clear|replace LEAF SUB REG VALUE` lines, and an aarch64 target's
hardware capability words are computed from its feature names (the order and
bit numbers of arch/arm64/include/uapi/asm/hwcap.h).
"""
import os
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))

HWCAP = ["fp", "asimd", "evtstrm", "aes", "pmull", "sha1", "sha2", "crc32", "atomics", "fphp", "asimdhp", "cpuid",
         "asimdrdm", "jscvt", "fcma", "lrcpc", "dcpop", "sha3", "sm3", "sm4", "asimddp", "sha512", "sve", "asimdfhm",
         "dit", "uscat", "ilrcpc", "flagm", "ssbs", "sb", "paca", "pacg"]


def rules(name):
    out = []
    with open(os.path.join(HERE, "rules", name + ".rules")) as f:
        for line in f:
            line = line.split("#", 1)[0].split()
            if line:
                out.append(" ".join(line))
    return out


def main():
    with open(os.path.join(HERE, "targets.toml"), "rb") as f:
        targets = tomllib.load(f)
    print("# generated by tools/mask/gen_profiles.py from tools/mask/targets.toml and tools/mask/rules; do not edit")
    for name, t in targets.items():
        print(f"\n[{t['subdir']}]")
        print(f"arch = {t['arch']}")
        if t["arch"] == "x86_64":
            for key in ("vendor", "family", "model", "model_name", "gcc_march"):
                print(f"{key} = {t[key]}")
            print("host_vendors = " + " ".join(t["host_vendors"]))
            print("needs = " + " ".join(t.get("needs", [])))
            print("drop_flags = " + " ".join(t["drop_flags"]))
            for r in rules(name):
                print("rule = " + r)
        else:
            hw = 0
            for feat in t["features"]:
                hw |= 1 << HWCAP.index(feat)
            for key in ("cpu_part", "gcc_cpu"):
                print(f"{key} = {t[key]}")
            print("features = " + " ".join(t["features"]))
            print(f"hwcap = {hw:#x}")
            print("hwcap2 = 0x0")


if __name__ == "__main__":
    sys.exit(main())
